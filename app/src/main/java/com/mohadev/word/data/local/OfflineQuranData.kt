    fun getOfflineVerses(surahId: Int): List<Ayah> {
        val predefined = predefinedSurahs[surahId]
        if (predefined != null && predefined.isNotEmpty()) {
            return predefined
        }

        // If not in special predefined list, generate structured offline representation matching the surah length & metadata
        val surahInfo = OfflineData.all114Surahs.find { it.id == surahId }
            ?: return emptyList()

        val count = surahInfo.versesCount
        val list = mutableListOf<Ayah>()

        // Add Basmalah if not At-Tawbah (9)
        if (surahId != 9 && surahId != 1) {
            list.add(
                Ayah(
                    id = surahId * 1000 + 1,
                    surahId = surahId,
                    numberInSurah = 1,
                    textUthmani = "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ",
                    tafsir = "أبتدئ قراءتي مستعينا باسم الله الرحمن الرحيم.",
                    page = surahInfo.startPage,
                    juz = surahInfo.juzNumber
                )
            )
        }

        for (i in (if (surahId != 9 && surahId != 1) 2 else 1)..count) {
            val ayahText = getOfflineAyahSampleText(surahId, i, surahInfo.nameArabic)
            val tafsirText = "آية كريمة من سورة ${surahInfo.nameArabic} المباركة (رقم $i) تحث على الإيمان والعمل الصالح والتقوى."
            list.add(
                Ayah(
                    id = surahId * 1000 + i,
                    surahId = surahId,
                    numberInSurah = i,
                    textUthmani = ayahText,
                    tafsir = tafsirText,
                    page = surahInfo.startPage + (i / 15),
                    juz = surahInfo.juzNumber
                )
            )
        }
        return list
    }

    fun getOfflineTafsir(surahId: Int): Map<Int, String> {
        val verses = getOfflineVerses(surahId)
        return verses.associate { it.numberInSurah to it.tafsir }
    }

